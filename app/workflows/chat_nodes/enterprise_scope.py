def looks_enterprise(text: str) -> bool:
    lowered = (text or "").lower()
    if not lowered.strip():
        return False
    if any(hint in lowered for hint in ENTERPRISE_HINTS):
        return True
    # 公司/企业主体 + 知识型问法（名称、业务、经营、简介、总部、成立等）。
    if re.search(r"(公司|企业|贵司|贵公司|我们).{0,12}(名称|叫什么|名字|全称|简称|简介|介绍|概况|业务|经营范围|主营|做什么|从事|哪些产品|哪些服务|总部|成立|多少人|在哪里|哪家)", lowered):
        return True
    return False


def looks_oa_policy(text: str) -> bool:
    """明确的 OA 制度/流程问题应优先使用制度库。"""
    lowered = (text or "").lower()
    return any(hint in lowered for hint in OA_POLICY_TERMS)


